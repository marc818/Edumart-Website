CREATE TABLE IF NOT EXISTS listings (
    listing_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seller_id BIGINT NOT NULL REFERENCES students(student_id),
    item_name VARCHAR(180) NOT NULL,
    category VARCHAR(100) NOT NULL,
    description TEXT,
    condition_label VARCHAR(60) NOT NULL,
    price_centavos INTEGER NOT NULL CHECK (price_centavos >= 0),
    photos JSONB,
    listing_status VARCHAR(32) NOT NULL DEFAULT 'PENDING_REVIEW' CHECK (
        listing_status IN (
            'PENDING_REVIEW',
            'APPROVED',
            'REJECTED',
            'SOLD',
            'REMOVED'
        )
    ),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS verification_audit_logs (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT REFERENCES students(student_id),
    listing_id BIGINT REFERENCES listings(listing_id),
    admin_id BIGINT NOT NULL REFERENCES admins(admin_id),
    action VARCHAR(80) NOT NULL,
    previous_status VARCHAR(40),
    new_status VARCHAR(40) NOT NULL,
    reason TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS orders (
    order_id VARCHAR(100) PRIMARY KEY,
    buyer_student_id BIGINT REFERENCES students(student_id),
    buyer_email VARCHAR(255) NOT NULL,
    payment_status VARCHAR(16) NOT NULL DEFAULT 'PENDING' CHECK (
        payment_status IN ('PENDING', 'PAID', 'FAILED', 'CANCELLED')
    ),
    receipt_number VARCHAR(120) UNIQUE,
    claim_token VARCHAR(128) UNIQUE,
    payment_reference VARCHAR(160),
    total_centavos INTEGER NOT NULL CHECK (total_centavos >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at TIMESTAMP
);
