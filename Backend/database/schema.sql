CREATE TABLE IF NOT EXISTS students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(160) NOT NULL,
    institutional_email VARCHAR(255) NOT NULL UNIQUE,
    student_number VARCHAR(80) NOT NULL UNIQUE,
    school VARCHAR(160) NOT NULL,
    college VARCHAR(160) NOT NULL,
    program VARCHAR(160) NOT NULL,
    password_hash VARCHAR(255),
    year_level VARCHAR(40),
    contact VARCHAR(40),
    document_path VARCHAR(500),
    verification_status VARCHAR(32) NOT NULL DEFAULT 'PENDING' CHECK (
        verification_status IN (
            'PENDING',
            'VERIFIED',
            'REJECTED',
            'SUSPENDED',
            'RESUBMISSION_REQUIRED'
        )
    ),
    verification_reason TEXT,
    verified_by BIGINT,
    verified_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS admins (
    admin_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255),
    role VARCHAR(20) NOT NULL DEFAULT 'ADMIN' CHECK (role IN ('ADMIN', 'SUPER_ADMIN')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
